def write_obj(path, v, f):
    trimesh.Trimesh(vertices=v, faces=f, process=False).export(path)


def prep_scan(t, gso, d):
    src = os.path.join(gso, t["src"])
    pieces = sorted((f for f in os.listdir(src) if f.startswith("model_collision_")), key=lambda s: int(re.findall(r"\d+", s)[0]))
    for f in pieces + ["model.obj", "texture.png"]:
        shutil.copy2(os.path.join(src, f), os.path.join(d, f))
    # The mass a MuJoCo-style loader gives the delivered MJCF (no inertial, density 1000 over every geom), from the audit.
    audit = {r["object"]: r for r in json.load(open(AUDIT))}
    loaded = audit[t["src"]]["as_provided"]["mass_kg"]
    return {"parts": [{"name": "body", "material": "unspecified", "density": 1000.0, "mode": "solid", "collision": pieces,
                       "visual": "model.obj", "texture": "texture.png", "area_factor": 0.5, "mass_from": "collision"}],
            "override": {"mass": loaded, "source": "as loaded: no inertial in the file, density 1000 over every geom"},
            "credit": GSO_CREDIT}


def prep_cad(t, vlmcad, d):
    src = os.path.join(vlmcad, t["src"])
    man = json.load(open(os.path.join(src, "manifest.json")))
    parts = []
    names = {"plastic_abs": "housing", "stainless_steel": "steel", "plastic_pp": "plastic", "silicone": "cord",
             "ceramic": "body", "porcelain": "body"}
    used = {}
    for i, p in enumerate(man["parts"]):
        m = trimesh.load(os.path.join(src, p["file"]), force="mesh")
        if len(m.faces) > 20000:
            m = m.simplify_quadric_decimation(face_count=20000)
        base = names.get(p["material"], p["material"])
        used[base] = used.get(base, 0) + 1
        name = base if used[base] == 1 else f"{base}_{used[base]}"
        vis = f"{name}_visual.obj"
        m.export(os.path.join(d, vis))
        hulls = coacd.run_coacd(coacd.Mesh(m.vertices, m.faces), threshold=0.04, max_convex_hull=24)
        files = []
        for j, (hv, hf) in enumerate(hulls):
            fn = f"{name}_c{j:02d}.obj"
            write_obj(os.path.join(d, fn), hv, hf)
            files.append(fn)
        parts.append({"name": name, "material": p["material"], "density": float(DENSITY[p["material"]]), "mode": "solid",
                      "collision": files, "visual": vis, "area_factor": 1.0, "mass_from": "visual"})
        print(f"  {name}: {len(m.faces)} faces, {len(files)} convex pieces")
    photos = []
    for f in ("view_34.png", "view_side.png"):
        if os.path.isfile(os.path.join(src, f)):
            shutil.copy2(os.path.join(src, f), os.path.join(d, f"source_{f}"))
            photos.append(f"source_{f}")
    return {"parts": parts, "credit": CAD_CREDIT, "photos": photos,
            "photo_note": "The photos the CAD was built from: the real object on a 1 cm grid, every fifth line darker."}


def prep_urdf(t, rcad, d):
    path = os.path.join(rcad, "urdf", t["src"])
    src_dir = os.path.dirname(path)
    text = open(path).read()
    clean = re.sub(r'(scale|size)="([^"]*)"', lambda m: '%s="%s"' % (m.group(1), " ".join(m.group(2).replace(",", " ").split())), text)
    open(os.path.join(d, "object.urdf"), "w").write(clean)
    for f in set(re.findall(r'filename="([^"]+)"', clean)):
        shutil.copy2(os.path.join(src_dir, f), os.path.join(d, f))
    # ReplicaCAD is authored Y-up, but some files already turn themselves Z-up with a root joint of rpy ~(pi/2, 0, 0).
    root = re.search(r'<joint name="(?:root_rotation|body_transform)"[^>]*>\s*<origin rpy="([^"]+)"', clean)
    rx = float(root.group(1).split()[0]) if root else 0.0
    euler = [0, 0, 0] if abs(rx - math.pi / 2) < 0.05 else [90, 0, 0]
    return {"urdf": "object.urdf", "self_collision": True, "euler": euler, "credit": RCAD_CREDIT}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gso", required=True)
    ap.add_argument("--vlmcad", required=True)
    ap.add_argument("--replicacad", required=True)
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    for t in TASKS:
        d = os.path.join(OUT, t["id"])
        shutil.rmtree(d, ignore_errors=True)
        os.makedirs(d)
        print(t["id"])
        extra = {"scan": lambda: prep_scan(t, a.gso, d), "cad": lambda: prep_cad(t, a.vlmcad, d),
                 "urdf": lambda: prep_urdf(t, a.replicacad, d)}[t["kind"]]()
        spec = {k: t[k] for k in ("id", "task", "kind", "label", "description", "complaint", "checks")}
        spec.update(extra)
        spec["scale"] = 1.0
        json.dump(spec, open(os.path.join(d, "asset.json"), "w"), indent=1)
    sizes = {t["id"]: round(sum(os.path.getsize(os.path.join(OUT, t["id"], f)) for f in os.listdir(os.path.join(OUT, t["id"]))) / 1e6, 1)
             for t in TASKS}
    print("MB per asset:", sizes, "total", round(sum(sizes.values()), 1))


if __name__ == "__main__":
    main()
